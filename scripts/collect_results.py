"""Gather the tables every run writes under checkpoints/ into results/ (tracked in git).

Copies ``*.md``, ``history.json``, ``ablation_results.json`` and ``*sweep*.json``
from each ``checkpoints/<run>/`` into ``results/<run>/`` and rewrites
``results/INDEX.md``. Weights stay in ``checkpoints/`` (gitignored).

    uv run python scripts/collect_results.py
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

KEEP = ("*.md", "history.json", "ablation_results.json", "*sweep*.json")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--checkpoints", default="checkpoints")
    parser.add_argument("--results", default="results")
    parser.add_argument(
        "--exclude", nargs="*", default=[], help="run directories to leave out (e.g. smoke runs)"
    )
    args = parser.parse_args()

    root = Path(args.checkpoints)
    out = Path(args.results)
    out.mkdir(parents=True, exist_ok=True)
    index: list[str] = [
        "# Results index",
        "",
        "Generated by `scripts/collect_results.py`; see `README.md` for the conclusions.",
        "",
    ]
    for run in sorted(p for p in root.iterdir() if p.is_dir() and p.name not in args.exclude):
        files = sorted(f for pattern in KEEP for f in run.rglob(pattern))
        if not files:
            continue
        index.append(f"## {run.name}")
        index.append("")
        for f in files:
            rel = f.relative_to(run)
            target = out / run.name / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)
            index.append(f"- [{rel}]({run.name}/{rel})")
        index.append("")
    (out / "INDEX.md").write_text("\n".join(index), encoding="utf-8")
    print(f"[*] {out / 'INDEX.md'} written")


if __name__ == "__main__":
    main()
